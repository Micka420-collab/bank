/** « crypto.exchange.add » → « Plateforme reliée… » ; un identifiant inconnu → « Crypto : exchange add ». */
export function labelAction(action: string): string {
  const known = ACTIONS[action];
  if (known) return known;
  const [domain, ...rest] = action.split(".");
  const tail = rest.join(" ").replaceAll("_", " ");
  const head = DOMAINS[domain ?? ""] ?? (domain ? domain[0]!.toUpperCase() + domain.slice(1) : "");
  return tail ? `${head} : ${tail}` : head || action;
}
